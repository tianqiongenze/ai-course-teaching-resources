def set_title(ts, text, font):
    tf = ts.text_frame
    first = None
    for p in tf.paragraphs:
        for r in p.runs:
            if first is None:
                col = None
                try:
                    if r.font.color and r.font.color.type is not None:
                        col = r.font.color.rgb
                except Exception:  # noqa: BLE001
                    col = None
                first = (r.font.size, r.font.bold, col)
    tf.clear()
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = text
    if first:
        if first[0]:
            r.font.size = first[0]
        if first[1] is not None:
            r.font.bold = first[1]
        try:
            if first[2]:
                r.font.color.rgb = first[2]
        except Exception:  # noqa: BLE001
            pass
    if font:
        r.font.name = font


def strip_clone(slide, keep_title):
    for sh in list(slide.shapes):
        top = (sh.top or 0) / 914400.0
        h = (sh.height or 0) / 914400.0
        if top <= 0.02 or top >= 7.0:
            continue
        if 1.2 <= top <= 1.4 and h < 0.15:
            continue
        if keep_title is not None and sh._element is keep_title._element:
            continue
        sh._element.getparent().remove(sh._element)


def inject_deck(path, deck_key, dry=False):
    prs = Presentation(path)
    titles = [slide_title(sl) for sl in prs.slides]
    if any(MARK in t for t in titles):
        return {"file": os.path.basename(path), "status": "skip(已注入)"}
    table = CONTENT.get(deck_key)
    if not table:
        return {"file": os.path.basename(path), "status": "skip(无内容表)"}
    # 定位知识详解页与卡号
    targets = []   # (idx0, card_id, card_title)
    for i, sl in enumerate(prs.slides):
        t = slide_title(sl)
        if t.startswith("知识详解"):
            cid, ctitle = "", t.split("：", 1)[-1]
            for sh in sl.shapes:
                if sh.has_text_frame:
                    m = re.match(r"^(B\d{2})", sh.text_frame.text.strip())
                    if m:
                        cid = m.group(1)
                        break
            if cid and cid in table:
                targets.append((i, cid, ctitle))
    if not targets:
        return {"file": os.path.basename(path), "status": "skip(无匹配知识卡)"}
    from inject97 import font_of
    font = font_of(prs.slides[0])
    for idx0, cid, ctitle in sorted(targets, reverse=True):
        card = table[cid]
        clones = []
        for _ in range(2):
            sl = clone_base(prs, idx0)
            ts = title_shape(sl)
            strip_clone(sl, ts)
            clones.append((sl, ts))
        src = "零基础补充讲解 · 原理句摘自本课工单 %s 知识卡；讲解为教师补充，口径与工单一致" % cid
        sl, ts = clones[0]
        if ts is not None:
            set_title(ts, "知识详解·大白话：%s（%s）" % (ctitle, cid), font)
        build_say(sl, card, font, src)
        sl, ts = clones[1]
        if ts is not None:
            set_title(ts, "知识详解·跟做：%s（%s）" % (ctitle, cid), font)
        build_do(sl, card, font, src)
        _reorder(prs, 2, idx0)
    _renumber_slide_num(prs)
    if not dry:
        rel = os.path.relpath(path, ROOT)
        bak = os.path.join(BAK, rel.replace(os.sep, "__"))
        os.makedirs(os.path.dirname(bak), exist_ok=True)
        if not os.path.exists(bak):
            shutil.copy2(path, bak)
        prs.save(path)
    return {"file": os.path.basename(path), "status": "ok",
            "cards": [c for _, c, _ in targets], "pages": 2 * len(targets)}


def main():
    dry = "--dry" in sys.argv
    only = None
    for a in sys.argv[1:]:
        if a.startswith("--deck="):
            only = a.split("=", 1)[1]
    report = []
    for f in sorted(glob.glob(os.path.join(ROOT, COURSE_DIR, "*.pptx"))):
        base = os.path.basename(f)
        if only and only not in base:
            continue
        key = next((k for k in CONTENT if base.startswith(k)), None)
        try:
            r = inject_deck(f, key, dry=dry) if key else \
                {"file": base, "status": "skip(不在内容表)"}
        except Exception as e:  # noqa: BLE001
            r = {"file": base, "status": "ERROR: %s" % e}
        report.append(r)
        print(r)
    if not dry:
        out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "inject104_manifest.json")
        json.dump(report, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
