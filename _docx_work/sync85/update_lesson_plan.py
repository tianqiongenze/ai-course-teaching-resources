def uniq_cells(row):
    out, seen = [], set()
    for c in row.cells:
        k = id(c._tc)
        if k in seen:
            continue
        seen.add(k)
        out.append(c)
    return out


def set_cell_text(cell, new_text):
    paras = cell.paragraphs
    first = paras[0]
    if not first.runs:
        first.add_run("")
    first.runs[0].text = new_text
    for r in first.runs[1:]:
        r.text = ""
    for p in paras[1:]:
        for r in p.runs:
            r.text = ""


def main():
    apply = "--apply" in sys.argv
    d = docx.Document(DOC)
    n = 0
    for idx, (wk, slot, rows) in enumerate(LESSONS, start=1):
        t = d.tables[idx]
        # ① 时间 + 课时（R1：形式|理实一体|课时|值|地点|值|时间|值）
        u1 = uniq_cells(t.rows[1])
        for i, c in enumerate(u1):
            if c.text.strip() == "时间" and i + 1 < len(u1):
                set_cell_text(u1[i + 1], "第%d周%s" % (wk, slot))
                n += 1
            if "4课时（2次×80分钟）" in c.text:
                set_cell_text(c, "4课时（160分钟）")
                n += 1
        # ② 任务实施 6 行
        for j, ri in enumerate(ROWS):
            u = uniq_cells(t.rows[ri])
            if len(u) < 5:
                print("  [WARN] 表%d R%d 列数异常 %d" % (idx, ri, len(u)))
                continue
            teacher, student, goal = rows[j]
            set_cell_text(u[1], teacher)
            set_cell_text(u[2], student)
            set_cell_text(u[3], goal)
            set_cell_text(u[4], "%d分钟" % TIMES[j])
            n += 4
        print("  表%-2d 第%-2d周 %-12s 已更新（任务实施6行/合计%d分钟）"
              % (idx, wk, slot, sum(TIMES)))
    print("\n合计 %d 处；%s" % (n, "已写入" if apply else "空跑"))
    if apply:
        d.save(DOC)
        print("已保存:", os.path.basename(DOC))


if __name__ == "__main__":
    main()
